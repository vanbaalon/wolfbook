'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { withVscodeStub, makeVscodeStub } = require('./_stub-vscode');
const calls = [], posts = [];
let complete;
const state = { account: 'connected', projects: [{ id: '0123456789abcdef01234567', name: 'Paper' }], recent: [] };
const stub = makeVscodeStub({ commands: { executeCommand: async (command, args) => {
    calls.push([command, args]);
    if (command === 'wolfbook.tex.overleafStatus') return state;
    if (command === 'wolfbook.tex.overleafOpenProject') return new Promise(resolve => { complete = resolve; });
} } });
const { WatchPanelProvider } = withVscodeStub(() => require('../../debugger/watchPanel'), stub);
(async () => {
    const provider = new WatchPanelProvider({});
    provider._view = { webview: { postMessage: message => posts.push(message) } };
    await provider._sendOverleafState(true);
    assert.deepStrictEqual(calls[0], ['wolfbook.tex.overleafStatus', { refresh: true }]);
    assert.strictEqual(posts.at(-1).command, 'overleafState');
    assert.strictEqual(posts.at(-1).state.projects[0].name, 'Paper');
    const task = provider._overleafAction('project', state.projects[0].id);
    await new Promise(resolve => setImmediate(resolve));
    assert.strictEqual(posts.at(-1).state.busy, true);
    const count = calls.length;
    await provider._overleafAction('git');
    assert.strictEqual(calls.length, count, 'opening actions are serialized while a project is loading');
    complete(); await task; await new Promise(resolve => setImmediate(resolve));
    assert.strictEqual(posts.at(-1).state.busy, false);
    await provider._overleafAction('run arbitrary command', 'workbench.action.reloadWindow');
    assert.strictEqual(calls.length, count + 1, 'only known Overleaf actions are accepted');
    const html = fs.readFileSync(path.join(__dirname, '../../debugger/watchPanel.js'), 'utf8');
    const js = fs.readFileSync(path.join(__dirname, '../../debugger/watchPanel.webview.js'), 'utf8');
    assert.match(html, /data-tab="overleaf"/);
    assert.match(html, /Browse projects · Live sync/);
    assert.match(html, /Open with Git/);
    assert.match(html.slice(html.indexOf('_sendCurrentState() {')), /this\._sendOverleafState\(\)/, 'state replays on scriptLoaded/visibility');
    assert.match(js, /button\.textContent = item\.name/, 'project names are text, never injected HTML');
    const pkg = JSON.parse(fs.readFileSync(path.join(__dirname, '../../../../package.json')));
    for (const command of ['wolfbook.tex.overleafOpenProject', 'wolfbook.tex.overleafOpenGit', 'wolfbook.tex.overleafConnectAccount']) assert.ok(pkg.contributes.commands.some(c => c.command === command));
    console.log('Overleaf sidebar: status replay, two modes, busy handling, safe actions and command contributions passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
